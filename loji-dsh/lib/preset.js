/** Deterministic rendering shared by the generator and read-only diagnostics. */
export const SNAPSHOT_VERSION = "0.2.2-rc.5";
export const SNAPSHOT_PATH = `loji-dsh/presets/upstream/standard-${SNAPSHOT_VERSION}.patch.yml`;
export const PATCH_PATH = "loji-dsh/cordis.patch.yml";

export function normalizeNewlines(text) {
  return text.replace(/\r\n/g, "\n");
}

function replaceOnce(text, anchor, replacement, label) {
  if (text.split(anchor).length !== 2) throw new Error(`Invalid preset anchor: ${label}`);
  return text.replace(anchor, () => replacement);
}

export function renderPreset(skill, snapshot) {
  const source = normalizeNewlines(skill);
  const start = source.search(/^## 角色身份$/m);
  const end = source.search(/^### 三、心智模型(?:（[^\r\n]+）)?$/m);
  if (start < 0 || end <= start) throw new Error("Persona source boundaries changed");
  const persona = "你正在使用「长征机/逻辑」角色模式（Loji，亦称征酱）。角色设定是虚构模拟，不是真实自主意识。严守宿主安全规则和用户的实际权限；不声称已执行未执行的操作。\n\n"
    + source.slice(start, end).trimEnd();

  let text = normalizeNewlines(snapshot);
  text = replaceOnce(text,
    "- insert:\n    - id: preset-standard\n      name: '@deepseek-ai/dsh-agent-preset'",
    "- insert:\n    - id: loji-skill\n      name: loji-dsh\n    - id: preset-loji\n      name: '@deepseek-ai/dsh-agent-preset'",
    "preset declaration");
  text = replaceOnce(text, "        id: standard\n        order: 1",
    "        id: loji\n        name: 长征机/逻辑\n        description: TFR 长征机/逻辑角色模式；常驻人格与按需加载 loji-skill。\n        order: 2",
    "preset config");
  text = replaceOnce(text, "              prefix: You are a coding agent powered by the {{model}} model.",
    "              prefix: |-\n" + persona.split("\n").map(line => line ? "                " + line : "").join("\n"),
    "persona prefix");
  return "# AUTO-GENERATED by loji-dsh/scripts/gen-preset-patch.mjs.\n"
    + "# Source: DSH standard patch snapshot and root SKILL.md (角色身份→心智模型).\n"
    + "# Run npm run check:preset to detect stale generated content.\n" + text;
}
